// Weapon definitions.
//
// Damage falls off over distance in explicit range bands (COD style), spray is a
// deterministic pattern with a small random component (Valorant/CS style), and
// every weapon carries the geometry spec its procedural model is built from.

export const SLOT = { PRIMARY: 0, SECONDARY: 1, MELEE: 2 };

/** Damage at a given distance from an ordered [distance, damage] band list. */
export function damageAtRange(bands, dist) {
  if (dist <= bands[0][0]) return bands[0][1];
  for (let i = 1; i < bands.length; i++) {
    if (dist <= bands[i][0]) {
      const [d0, v0] = bands[i - 1];
      const [d1, v1] = bands[i];
      const t = (dist - d0) / (d1 - d0 || 1);
      return v0 + (v1 - v0) * t;
    }
  }
  return bands[bands.length - 1][1];
}

